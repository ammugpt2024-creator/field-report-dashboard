-- Somewhere for failures to land.
--
-- Today a crash or a failed save is visible only in the browser console of
-- the person it happened to, so problems reach us when somebody thinks to
-- mention them. This is the smallest thing that fixes that: the app records
-- what broke, and an admin can read it.
--
-- Deliberately not a third-party service. The records stay in your database,
-- under the same company rules as everything else.

create table if not exists public.client_errors (
  id bigint generated by default as identity primary key,
  company_id uuid default public.auth_company_id() references public.companies (id) on delete set null,
  user_id uuid default auth.uid() references auth.users (id) on delete set null,
  occurred_at timestamptz not null default now(),
  kind text not null default 'error' check (kind in ('error', 'unhandled_rejection', 'reported')),
  message text not null,
  context text,                 -- the screen or action, e.g. "daily-log:submit"
  stack text,
  path text,                    -- in-app route, never a signed URL
  user_agent text
);

create index if not exists idx_client_errors_occurred on public.client_errors (occurred_at desc);
create index if not exists idx_client_errors_company on public.client_errors (company_id, occurred_at desc);

alter table public.client_errors enable row level security;

-- Anyone signed in can report what broke for them; nobody can write an entry
-- in someone else's name or another company's.
drop policy if exists "Members record their own errors" on public.client_errors;
create policy "Members record their own errors" on public.client_errors
  for insert to authenticated
  with check (
    user_id = auth.uid()
    and (company_id is null or company_id = public.auth_company_id())
  );

-- Reading is for the people who act on it: company admins for their own
-- company, platform admins across the platform.
drop policy if exists "Admins read error reports" on public.client_errors;
create policy "Admins read error reports" on public.client_errors
  for select to authenticated
  using (
    public.is_platform_admin()
    or (company_id = public.auth_company_id() and public.has_company_role(array['company_admin']))
  );

